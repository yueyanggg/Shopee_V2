export function findSimilarProducts(
  query: string,
  allProducts: Product[],
  excludeIds: string[] = []
): Product[] {
  const q = query.trim().toLowerCase();
  const keywordMap: { tokens: string[]; categoryIds: string[]; titleHints?: string[] }[] = [
    {
      tokens: ['phone', 'case', 'cover', 'iphone', 'samsung', 'pixel', 'magsafe', 'screen'],
      categoryIds: ['mobile', 'accessories'],
    },
    {
      tokens: ['earbud', 'airpod', 'headset', 'earphone', 'audio', 'speaker', 'music'],
      categoryIds: ['audio'],
    },
    {
      tokens: ['coffee', 'tea', 'latte', 'matcha', 'grocery', 'groceries', 'drink', 'kitchen'],
      categoryIds: ['groceries', 'kitchen'],
    },
    {
      tokens: ['desk', 'laptop', 'monitor', 'keyboard', 'mouse', 'work', 'office', 'charger'],
      categoryIds: ['electronics', 'gaming', 'home'],
    },
    {
      tokens: ['skin', 'cream', 'serum', 'face', 'moisturizer', 'beauty'],
      categoryIds: ['beauty', 'fragrance'],
    },
    {
      tokens: ['shoe', 'sneaker', 'bag', 'backpack', 'travel', 'jacket', 'bottle'],
      categoryIds: ['footwear', 'bags', 'travel', 'fashion', 'fitness'],
    },
  ];

  const matchedCategoryIds = new Set<string>();
  for (const entry of keywordMap) {
    if (entry.tokens.some((t) => q.includes(t))) {
      entry.categoryIds.forEach((id) => matchedCategoryIds.add(id));
    }
  }

  const candidates = allProducts.filter((p) => !excludeIds.includes(p.id));
  if (matchedCategoryIds.size > 0) {
    const catMatches = candidates.filter((p) => matchedCategoryIds.has(p.categoryId));
    if (catMatches.length > 0) {
      return catMatches.slice(0, 6);
    }
  }

  // Fallback to partial word overlap or highest-rated bestsellers
  const words = q.split(/\s+/).filter((w) => w.length >= 2);
  if (words.length > 0) {
    const partial = candidates.filter((p) =>
      words.some(
        (w) =>
          p.title.toLowerCase().includes(w) ||
          p.categoryName.toLowerCase().includes(w) ||
          p.description.toLowerCase().includes(w)
      )
    );
    if (partial.length > 0) return partial.slice(0, 6);
  }

  return [...candidates].sort((a, b) => b.soldCount - a.soldCount).slice(0, 6);
}

export function computeVoucherDiscount(
  voucher: Voucher,
  subtotal: number,
  baseShipping: number
): number {
  if (subtotal < voucher.minSpend) return 0;
  if (voucher.discountType === 'fixed') {
    return voucher.value;
  }
  if (voucher.discountType === 'percent') {
    const raw = (subtotal * voucher.value) / 100;
    return voucher.maxCap ? Math.min(raw, voucher.maxCap) : raw;
  }
  if (voucher.discountType === 'shipping') {
    return Math.min(baseShipping, voucher.value);
  }
  return 0;
}

export function getBestVoucherForSubtotal(
  vouchers: Voucher[],
  subtotal: number,
  baseShipping: number
): { voucher: Voucher | null; savings: number } {
  let bestVoucher: Voucher | null = null;
  let bestSavings = 0;
  for (const v of vouchers) {
    const savings = computeVoucherDiscount(v, subtotal, baseShipping);
    if (savings > bestSavings) {
      bestSavings = savings;
      bestVoucher = v;
    }
  }
  return { voucher: bestVoucher, savings: bestSavings };
}


